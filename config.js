function comicScene({ badge, badgeColor, theme = 'paper', groups }) {
    const rm = {}, hm = {}, fb = [], hfb = [];
    groups.forEach(g => {
        if (g.always) return;
        if (g.w) (rm[g.w] = rm[g.w] || []).push(g.id);
        if (g.t !== undefined) fb.push([g.id, g.t]);
        if (g.hw) (hm[g.hw] = hm[g.hw] || []).push(g.id);
        if (g.ht !== undefined) hfb.push([g.id, g.ht]);
    });
    const bc = badgeColor || (theme === 'blue' ? THEME.bpHi : THEME.accent);
    const bt = theme === 'blue' ? '#0f3d7a' : '#fff';
    const gh = groups.map(g => `<g transform="translate(${g.x || 0} ${g.y || 0})"><g transform="scale(${g.s || 1})"><g id="${g.id}" class="${g.always ? 'always' : 'revealgrp'}">${g.svg}</g></g></g>`).join('\n');
    const html = `<!DOCTYPE html><html><head><meta charset="utf-8"><style>
  *{box-sizing:border-box;margin:0;padding:0}
  html,body{width:1080px;height:1920px;overflow:hidden;${THEMES[theme]};font-family:Georgia,'Times New Roman',serif;color:${THEME.ink}}
  .badge{position:absolute;top:120px;left:50%;transform:translateX(-50%) rotate(-2deg);background:${bc};color:${bt};
    font:900 54px Impact,'Arial Black',sans-serif;padding:4px 30px;box-shadow:6px 6px 0 ${THEME.shadow};white-space:nowrap;z-index:10;opacity:0;transition:opacity .4s ease}
  .badge.on{opacity:1}
  svg#stage{position:absolute;left:40px;top:260px;width:1000px;height:1480px;overflow:visible}
  .revealgrp{opacity:0;transform:scale(.85);transform-box:fill-box;transform-origin:center;transition:opacity .45s ease,transform .45s cubic-bezier(.2,1.4,.4,1)}
  .revealgrp.on{opacity:1;transform:scale(1)}
  .revealgrp.fadeout{opacity:0 !important;transform:scale(.7) !important;pointer-events:none}
  ${CSS_ANIM}
</style></head><body>
  <div class="badge" id="badge">${badge}</div>
  <svg id="stage" viewBox="0 0 1000 1480" xmlns="http://www.w3.org/2000/svg">
    ${gh}
  </svg>
<script>${REVEAL_JS}
  wire(${JSON.stringify(rm)}, ${JSON.stringify(hm)}, ${JSON.stringify(fb)}, ${JSON.stringify(hfb)});
  window.addEventListener('apexframe', function(){ document.getElementById('badge').classList.add('on'); }, { once: true });
</script></body></html>`;
    return {
        type: 'html-record', html, audioSync: true, cursor: false, waitFor: '[data-ready="1"]', fps: 30,
        viewport: { width: 1080, height: 1920 }, x: 0, y: 0, width: 1080, height: 1920, fit: 'cover'
    };
}
const scene = (bg, tts, layer, transition = 'fade') => ({
    transition, tts: { text: tts, pauseAfter: .25 }, captions: false,
    layers: [{ type: 'background', color: bg }, layer]
});

// ── async build: fetch unDraw illustration via npm, recolor, inline ──
async function buildConfig() {
    // 1. Create an unDraw client (uses fetch under the hood)
    const undraw = createUndrawClient();

    // 2. Search for an illustration by concept
    const results = await undraw.search({ query: 'idea', limit: 1 });
    if (!results.length) throw new Error('No unDraw illustration found for "idea"');
    const { svgUrl } = results[0];

    // 3. Fetch the raw SVG markup
    const rawSvg = await undraw.fetchSvg(svgUrl);

    // 4. Recolor its default accent (#6c63ff) to your THEME.accent
    const illustration = recolorIllustration(rawSvg, THEME.accent);

    // 5. Build scenes using the inlined SVG string
    const S = [];

    // ── 0 HOOK — real unDraw illustration ────────────────────────
    S.push(scene(THEME.paper,
        "Here is a real illustration from unDraw, fetched at build time. It is a full scene, not an icon, and it was recolored to match this theme.",
        comicScene({ badge: 'REAL unDraw ILLUSTRATION', theme: 'paper', groups: [
            { id: 'hero', x: 500, y: 660, s: 2.1, w: 'illustration', t: 1.0, svg: `<g ${an('float', 2)}>${illustration}</g>` },
            { id: 'lbl', x: 500, y: 1220, w: 'scene', t: 3.8, svg: T(0, 0, 'MULTI-LAYER SVG', 48, THEME.accent) },
            { id: 'sub', x: 500, y: 1300, w: 'build', t: 5.0, svg: T(0, 0, 'fetched via npm · recolored · inlined', 32, THEME.ink) }
        ] })));

    // ── 1 CTA ─────────────────────────────────────────────────────
    S.push(scene(THEME.paper,
        "The whole illustration lives inside the config as a string. No runtime CDN call, no async gate, no network dependency during recording.",
        comicScene({ badge: 'INLINED AT BUILD TIME', badgeColor: THEME.accent2, groups: [
            { id: 'icon', x: 500, y: 520, s: 3, w: 'string', t: 1.2, svg: `<g ${an('pulse', 1)}>${illustration}</g>` },
            { id: 'line1', x: 500, y: 1020, w: 'config', t: 3.5, svg: T(0, 0, 'SVG STRING IN THE CONFIG', 44, THEME.accent) },
            { id: 'line2', x: 500, y: 1100, w: 'network', t: 5.0, svg: T(0, 0, 'NO RUNTIME NETWORK', 44, THEME.accent2) },
            { id: 'sub', x: 500, y: 1320, w: 'subscribe', t: 7.5, svg: `<g ${an('pulse', .8)}><rect x="-190" y="-44" width="380" height="88" rx="18" fill="${THEME.accent}" stroke="${THEME.ink}" stroke-width="7"/><text x="0" y="18" font-size="54" text-anchor="middle" fill="#fff" font-family="${FI}">SUBSCRIBE</text></g>` }
        ] })));

    // ── export ────────────────────────────────────────────────────
    const TRANS = ['fade', 'wipe-left'];
    return {
        output: { title: 'npm-illustration-test', format: 'portrait', fps: 30, crf: 23, preset: 'medium' },
        defaults: { voice: 'am_adam', speed: 1.02, transition: 'fade', transitionDuration: 0.3 },
        scenes: S.map((s, i) => Object.assign(s, { transition: TRANS[i] || 'fade' })),
    };
}

// Export a promise — the engine must await it before starting the render.
module.exports = buildConfig();